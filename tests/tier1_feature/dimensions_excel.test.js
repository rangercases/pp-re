import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, '../..');

const indexHtml = fs.readFileSync(path.resolve(projectRoot, 'index.html'), 'utf8');

function extractFnBody(source, signature, label) {
  const pattern = new RegExp(signature.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + ' \\{([\\s\\S]*?)\\n    \\}');
  const match = source.match(pattern);
  assert.ok(match, `${label} must be present in index.html`);
  return match[1];
}

function loadDimExcelFns() {
  const names = [
    'collectDimensionExcelRows(dimensions)',
    'dimXlsxEscapeXml(s)',
    'dimXlsxCell(ref, value, isHeader)',
    'dimXlsxCrc32(bytes)',
    'dimXlsxZipStored(files)',
    'buildDimensionsXlsxBytes(rows)'
  ];
  const code = names.map(sig => {
    const name = sig.slice(0, sig.indexOf('('));
    return `function ${sig} {${extractFnBody(indexHtml, `function ${sig}`, name)}}`;
  }).join('\n');
  return new Function(`${code}\nreturn { collectDimensionExcelRows, buildDimensionsXlsxBytes };`)();
}

// ─────────────────────────────────────────────────────────────────────────────
// DIM-XLSX (v4.7.0) — Dimensions → Excel export, Pre-Production only.
// Hung's spec (2026-11-17): icon button inside the Dimensions section,
// 4 columns (Name / Drawing / Actual / Unit), no photos, rows without a
// name or without any value are skipped.
// ─────────────────────────────────────────────────────────────────────────────

describe('TC-DIMX: dimensions Excel export', () => {
  it('TC-DIMX.1: the Excel icon button lives in the Dimensions section head', () => {
    const start = indexHtml.indexOf('id="sec_dimensions"');
    assert.ok(start !== -1, 'sec_dimensions must exist');
    const end = indexHtml.indexOf('id="sec_assembly"', start);
    const block = indexHtml.slice(start, end === -1 ? undefined : end);
    assert.ok(block.includes('id="btnDimExcel"'), 'button #btnDimExcel inside sec_dimensions');
    assert.ok(block.includes('onclick="exportDimensionsExcel()"'), 'button wired to exportDimensionsExcel()');
    assert.ok(block.indexOf('id="btnDimExcel"') < block.indexOf('id="dimGrid"'), 'button sits in the head, above the grid');
  });

  it('TC-DIMX.2: the button is gated to Pre-Production in showSection', () => {
    const body = extractFnBody(indexHtml, 'function showSection(i)', 'showSection');
    assert.ok(body.includes("getElementById('btnDimExcel')"), 'showSection touches #btnDimExcel');
    assert.ok(body.includes("=== 'pre-production'"), 'visibility checks the pre-production module');
  });

  it('TC-DIMX.3: row collection skips nameless and value-less rows, merges units', () => {
    const { collectDimensionExcelRows } = loadDimExcelFns();
    const rows = collectDimensionExcelRows([
      { name: 'Width', drawing: '1200', actual: '1201', drawingUnit: 'mm', actualUnit: 'mm' },
      { name: '  ', drawing: '300', actual: '300', drawingUnit: 'mm', actualUnit: 'mm' },
      { name: 'Empty', drawing: '', actual: ' ', drawingUnit: 'mm', actualUnit: 'mm' },
      { name: 'Half', drawing: '450', actual: '', drawingUnit: 'mm', actualUnit: 'mm' },
      { name: 'Mixed', drawing: '100', actual: '4', drawingUnit: 'mm', actualUnit: 'in' },
      { name: 'NoUnits', drawing: '10', actual: '10' }
    ]);
    assert.equal(rows.length, 4);
    assert.deepEqual(rows[0], { name: 'Width', drawing: '1200', actual: '1201', unit: 'mm' });
    assert.equal(rows[1].name, 'Half');
    assert.equal(rows[2].unit, 'mm/in', 'differing units are both shown');
    assert.equal(rows[3].unit, 'mm', 'missing units default to mm');
    assert.deepEqual(collectDimensionExcelRows(null), []);
    assert.deepEqual(collectDimensionExcelRows([]), []);
  });

  it('TC-DIMX.4: generated bytes are a valid stored-zip xlsx with typed cells', () => {
    const { buildDimensionsXlsxBytes } = loadDimExcelFns();
    const bytes = buildDimensionsXlsxBytes([
      { name: 'Overall <width>', drawing: '1200', actual: '1201.5', unit: 'mm' }
    ]);
    assert.equal(String.fromCharCode(bytes[0], bytes[1]), 'PK', 'zip magic');
    const text = new TextDecoder('latin1').decode(bytes);
    assert.ok(text.includes('[Content_Types].xml'), 'content types part present');
    assert.ok(text.includes('xl/worksheets/sheet1.xml'), 'sheet part present');
    assert.ok(text.includes('Overall &lt;width&gt;'), 'names are XML-escaped');
    assert.ok(text.includes('<v>1200</v>'), 'numeric drawing exported as a number cell');
    assert.ok(text.includes('<v>1201.5</v>'), 'numeric actual exported as a number cell');
    assert.ok(text.includes('>Name</t>'), 'header row present');
    // End-of-central-directory signature PK\x05\x06 closes the file.
    assert.ok(text.includes('PK\x05\x06'), 'zip end record present');
  });

  it('TC-DIMX.5: export refuses to download when there is no data', () => {
    const body = extractFnBody(indexHtml, 'function exportDimensionsExcel()', 'exportDimensionsExcel');
    assert.ok(body.includes('collectDimensionExcelRows(D.dimensions)'), 'reads the open report dimensions');
    assert.ok(body.includes("showToast('No dimension data to export')"), 'empty state is a toast, not a file');
    assert.ok(body.includes('Dimensions.xlsx'), 'download keeps the Dimensions.xlsx name');
  });
});
