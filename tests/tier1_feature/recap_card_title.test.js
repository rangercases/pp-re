import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, '../..');

const indexHtml = fs.readFileSync(path.resolve(projectRoot, 'index.html'), 'utf8');

function extractFnBody(source, signature, label) {
  const pattern = new RegExp(signature.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + ' \\{([\\s\\S]*?)\\n    \\}');
  const match = source.match(pattern);
  assert.ok(match, `${label} must be present in index.html`);
  return match[1];
}

// INH-2/F6 (v4.6.0): hub cards are generated by renderHubCards() from
// MODULE_THEMES.hub. Evaluate the real config + renderer against a stub
// document, then slice one GENERATED card out of the result by its card id
// so assertions never leak into neighbouring cards (same discipline as the
// old static-markup slicing, one level up).
function generatedHubHtml() {
  const tm = indexHtml.match(/const MODULE_THEMES = \{([\s\S]*?)\n    \};/);
  assert.ok(tm, 'MODULE_THEMES must be present in index.html');
  const themes = new Function(
    'DEFAULT_MODULES_PREPROD', 'DEFAULT_MODULES_PROTOTYPE', 'DEFAULT_MODULES_RECAP',
    `return {${tm[1]}}`
  )([], [], []);
  const hexBody = extractFnBody(indexHtml, 'function hexToRgba(hex, alpha)', 'hexToRgba');
  const hubBody = extractFnBody(indexHtml, 'function renderHubCards()', 'renderHubCards');
  const grid = { innerHTML: '' };
  const docStub = { getElementById: (id) => (id === 'hubModuleGrid' ? grid : null) };
  const hexToRgba = new Function('hex', 'alpha', hexBody);
  new Function('document', 'MODULE_THEMES', 'hexToRgba',
    `function renderHubCards() {${hubBody}}\nrenderHubCards();`)(docStub, themes, hexToRgba);
  return grid.innerHTML;
}

const hubHtml = generatedHubHtml();

function cardBlock(cardId, nextCardId) {
  const start = hubHtml.indexOf(`id="${cardId}"`);
  assert.ok(start !== -1, `${cardId} must be present in the generated hub`);
  const end = nextCardId ? hubHtml.indexOf(`id="${nextCardId}"`, start) : hubHtml.length;
  assert.ok(end !== -1, `${nextCardId} must follow ${cardId} in the generated hub`);
  return hubHtml.slice(start, end);
}

const preProdBlock = cardBlock('cardModulePreProd', 'cardModulePrototype');
const prototypeBlock = cardBlock('cardModulePrototype', 'cardModuleRecap');
const recapBlock = cardBlock('cardModuleRecap', null);

function cardText(block, cls, label) {
  const match = block.match(new RegExp(`<div class="${cls}">([^<]*)</div>`));
  assert.ok(match, `${label} card must contain a .${cls} text node`);
  return match[1];
}

// ─────────────────────────────────────────────────────────────────────────────
// TC-CARD1 — Module 03 hub card title/tagline match modules 01/02 (v4.1.9)
// ─────────────────────────────────────────────────────────────────────────────
describe('TC-CARD1: Recap hub card title is "Recap", tagline matches 01/02 (v4.1.9)', () => {
  it('TC-CARD1.1: the Recap card title is "Recap" and its tagline is "Sample Review Report"', () => {
    assert.ok(recapBlock.includes('id="cardModuleRecap"'), 'slice must be the Recap card');
    assert.equal(cardText(recapBlock, 'craft-card-title', 'Recap'), 'Recap');
    assert.equal(cardText(recapBlock, 'craft-card-tagline', 'Recap'), 'Sample Review Report');
    assert.ok(
      !recapBlock.includes('Overview &amp; Watch Out'),
      'the old "Overview & Watch Out" tagline must be gone from the Recap card'
    );
  });

  it('TC-CARD1.2: all three active cards share the same tagline; 01/02 titles unchanged', () => {
    const tagline01 = cardText(preProdBlock, 'craft-card-tagline', 'Pre-Production');
    const tagline02 = cardText(prototypeBlock, 'craft-card-tagline', 'Prototype');
    const tagline03 = cardText(recapBlock, 'craft-card-tagline', 'Recap');
    assert.equal(tagline01, 'Sample Review Report');
    assert.equal(tagline02, tagline01, 'module 02 tagline must match module 01');
    assert.equal(tagline03, tagline01, 'module 03 tagline must match modules 01/02');
    assert.equal(cardText(preProdBlock, 'craft-card-title', 'Pre-Production'), 'Pre-Production');
    assert.equal(cardText(prototypeBlock, 'craft-card-title', 'Prototype'), 'Prototype');
  });
});
