import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, '../..');

const indexHtml = fs.readFileSync(path.resolve(projectRoot, 'index.html'), 'utf8');

function extractFnBody(source, signature, label) {
  const pattern = new RegExp(signature.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + ' \\{([\\s\\S]*?)\\n    \\}');
  const match = source.match(pattern);
  assert.ok(match, `${label} must be present in index.html`);
  return match[1];
}

// INH-2/F6 (v4.6.0): the hub cards are no longer static HTML — they are
// generated at runtime by renderHubCards() from MODULE_THEMES.hub into
// #hubModuleGrid. Evaluate the real config + renderer against a stub
// document and run the same assertions over the GENERATED markup.
function generatedHubHtml() {
  const tm = indexHtml.match(/const MODULE_THEMES = \{([\s\S]*?)\n    \};/);
  assert.ok(tm, 'MODULE_THEMES must be present in index.html');
  const themes = new Function(
    'DEFAULT_MODULES_PREPROD', 'DEFAULT_MODULES_PROTOTYPE', 'DEFAULT_MODULES_RECAP',
    `return {${tm[1]}}`
  )([], [], []);
  const hexBody = extractFnBody(indexHtml, 'function hexToRgba(hex, alpha)', 'hexToRgba');
  const hubBody = extractFnBody(indexHtml, 'function renderHubCards()', 'renderHubCards');
  const grid = { innerHTML: '' };
  const docStub = { getElementById: (id) => (id === 'hubModuleGrid' ? grid : null) };
  const hexToRgba = new Function('hex', 'alpha', hexBody);
  new Function('document', 'MODULE_THEMES', 'hexToRgba',
    `function renderHubCards() {${hubBody}}\nrenderHubCards();`)(docStub, themes, hexToRgba);
  return grid.innerHTML;
}

// ─────────────────────────────────────────────────────────────────────────────
// TC-HUB1 — Hub shows exactly the 3 active modules; module 04 removed (v4.2.1)
// ─────────────────────────────────────────────────────────────────────────────
describe('TC-HUB1: hub has exactly 3 active cards, module 04 Mass Production is gone (v4.2.1)', () => {
  it('TC-HUB1.1: the generated hub contains exactly the 01/02/03 cards, in order, unrenumbered', () => {
    assert.ok(indexHtml.includes('id="hubModuleGrid"'), 'the hub grid container must exist in index.html');
    assert.ok(indexHtml.includes('function renderHubCards()'), 'cards must be generated by renderHubCards');
    const hub = generatedHubHtml();
    const cardIds = [...hub.matchAll(/<div class="craft-module-card" id="(cardModule\w+)"/g)].map(m => m[1]);
    assert.deepEqual(
      cardIds,
      ['cardModulePreProd', 'cardModulePrototype', 'cardModuleRecap'],
      'hub must contain exactly the 3 active module cards in order'
    );
    const numBoxes = [...hub.matchAll(/craft-card-num-box"[^>]*>(\d{2})</g)].map(m => m[1]);
    assert.deepEqual(numBoxes, ['01', '02', '03'], 'num boxes must stay 01/02/03 — no renumbering, no 04');
  });

  it('TC-HUB1.2: no module 04 placeholder markup remains anywhere in index.html', () => {
    for (const gone of ['Mass Production', 'Factory Inspection', '[UPCOMING]', 'MODULE 04', '🏭', "'mass-production'"]) {
      assert.ok(!indexHtml.includes(gone), `"${gone}" must no longer exist in index.html`);
    }
    assert.ok(!generatedHubHtml().includes('PLANNED'), 'the PLANNED badge of the removed card must be gone from the hub');
  });
});
